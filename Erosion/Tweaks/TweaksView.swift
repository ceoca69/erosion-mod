// MARK: - Supervision / configuration-profile tweaks

private enum SupervisionProfileError: LocalizedError {
    case invalidURL
    case emptyValue
    case serverStartFailed

    var errorDescription: String? {
        switch self {
        case .invalidURL: return "The URL must begin with http:// or https://."
        case .emptyValue: return "Please fill in the required fields."
        case .serverStartFailed: return "Failed to start the local profile server."
        }
    }
}

private struct SupervisionProfile {
    let fileName: String
    let displayName: String
    let payloadType: String
    let payload: [String: Any]

    func data() throws -> Data {
        let rootUUID = UUID().uuidString
        let payloadUUID = UUID().uuidString
        var payloadDictionary = payload
        payloadDictionary["PayloadType"] = payloadType
        payloadDictionary["PayloadIdentifier"] = "com.erosion.supervision.\(payloadType).\(payloadUUID)"
        payloadDictionary["PayloadUUID"] = payloadUUID
        payloadDictionary["PayloadVersion"] = 1
        payloadDictionary["PayloadDisplayName"] = displayName
        payloadDictionary["PayloadDescription"] = "Generated by Erosion"
        payloadDictionary["PayloadOrganization"] = "Erosion"

        let root: [String: Any] = [
            "PayloadContent": [payloadDictionary],
            "PayloadDisplayName": displayName,
            "PayloadIdentifier": "com.erosion.supervision.profile.\(rootUUID)",
            "PayloadOrganization": "Erosion",
            "PayloadRemovalDisallowed": false,
            "PayloadType": "Configuration",
            "PayloadUUID": rootUUID,
            "PayloadVersion": 1
        ]
        return try PropertyListSerialization.data(fromPropertyList: root, format: .xml, options: 0)
    }
}

private final class SupervisionProfileServer: NSObject {
    private var listener: NWListener?
    private let port: NWEndpoint.Port = 51925
    private var data = Data()
    private var fileName = "profile.mobileconfig"
    private var backgroundTask: UIBackgroundTaskIdentifier = .invalid
    private var readyCompletion: ((Result<URL, Error>) -> Void)?

    func start(profile: SupervisionProfile, completion: @escaping (Result<URL, Error>) -> Void) {
        do {
            data = try profile.data()
            fileName = profile.fileName
            readyCompletion = completion

            listener?.cancel()
            listener = try NWListener(using: .tcp, on: port)

            listener?.stateUpdateHandler = { [weak self] state in
                guard let self else { return }
                switch state {
                case .ready:
                    let url = URL(string: "http://127.0.0.1:51925/")!
                    DispatchQueue.main.async {
                        self.readyCompletion?(.success(url))
                        self.readyCompletion = nil
                    }
                case .failed(let error):
                    DispatchQueue.main.async {
                        self.readyCompletion?(.failure(error))
                        self.readyCompletion = nil
                    }
                    self.stop()
                case .cancelled:
                    break
                default:
                    break
                }
            }

            listener?.newConnectionHandler = { [weak self] connection in
                guard let self else { return }
                connection.start(queue: .main)
                self.handle(connection: connection)
            }

            backgroundTask = UIApplication.shared.beginBackgroundTask(withName: "Erosion Profile Server") { [weak self] in
                self?.stop()
            }

            listener?.start(queue: .main)
        } catch {
            completion(.failure(error))
        }
    }

    private func handle(connection: NWConnection) {
        connection.receive(minimumIncompleteLength: 1, maximumLength: 65536) { [weak self, weak connection] _, _, _, _ in
            guard let self, let connection else { return }

            var response = "HTTP/1.1 200 OK\r\n"
            response += "Content-Type: application/x-apple-aspen-config\r\n"
            response += "Content-Length: \(self.data.count)\r\n"
            response += "Content-Disposition: attachment; filename=\"\(self.fileName)\"\r\n"
            response += "Pragma: no-cache\r\n"
            response += "Expires: 0\r\n"
            response += "Connection: close\r\n"
            response += "\r\n"

            var responseData = Data(response.utf8)
            responseData.append(self.data)

            connection.send(content: responseData, completion: .contentProcessed { [weak self] _ in
                connection.cancel()
                self?.stop()
            })
        }
    }

    func stop() {
        listener?.cancel()
        listener = nil
        if backgroundTask != .invalid {
            UIApplication.shared.endBackgroundTask(backgroundTask)
            backgroundTask = .invalid
        }
    }
}

private struct SupervisionSafariView: UIViewControllerRepresentable {
    let url: URL

    func makeUIViewController(context: Context) -> SFSafariViewController {
        SFSafariViewController(url: url)
    }

    func updateUIViewController(_ uiViewController: SFSafariViewController, context: Context) {}
}

private enum SupervisionInstaller {
    // Keep the server strongly retained. Lithium relies on its listener retaining
    // the server through its connection handler; we make that lifetime explicit.
    static var server: SupervisionProfileServer?

    @MainActor
    static func install(_ profile: SupervisionProfile) {
        let server = SupervisionProfileServer()
        self.server = server

        server.start(profile: profile) { result in
            switch result {
            case .success(let url):
                DispatchQueue.main.async {
                    // Use the same installation path as Lithium: present Safari's
                    // web view and let iOS handle the application/x-apple-aspen-config
                    // response as a configuration profile.
                    guard let scene = UIApplication.shared.connectedScenes
                        .compactMap({ $0 as? UIWindowScene })
                        .first(where: { $0.activationState == .foregroundActive }),
                          let window = scene.windows.first(where: { $0.isKeyWindow }),
                          var presenter = window.rootViewController else {
                        Alertinator.shared.alert(title: "Failed to install profile!", body: "Could not find the active application window.")
                        return
                    }

                    while let presented = presenter.presentedViewController {
                        presenter = presented
                    }

                    presenter.present(
                        UIHostingController(rootView: SupervisionSafariView(url: url)),
                        animated: true
                    )
                }
            case .failure(let error):
                Alertinator.shared.alert(title: "Failed to install profile!", body: error.localizedDescription)
                self.server = nil
            }
        }
    }
}

