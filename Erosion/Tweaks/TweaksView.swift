private struct SupervisionRestrictionsView: View {
    private struct Item: Identifiable {
        let id = UUID()
        let title: String
        let key: String
        let icon: String
    }

    @State private var values: [String: Bool] = [:]

    private let persistencePrefix = "Erosion.Supervision.Restriction."

    private let home = [
        Item(title: "Allow App Clips", key: "allowAppClips", icon: "app.badge"),
        Item(title: "Allow App Installation", key: "allowAppInstallation", icon: "arrow.down.app"),
        Item(title: "Allow App Removal", key: "allowAppRemoval", icon: "trash"),
        Item(title: "Allow Safari", key: "allowSafari", icon: "safari"),
        Item(title: "Allow Camera", key: "allowCamera", icon: "camera"),
        Item(title: "Allow Wallpaper Modification", key: "allowWallpaperModification", icon: "photo"),
        Item(title: "Allow Screen Shot", key: "allowScreenShot", icon: "camera.viewfinder")
    ]
    private let system = [
        Item(title: "Allow Game Center", key: "allowGameCenter", icon: "gamecontroller"),
        Item(title: "Allow Siri", key: "allowSiri", icon: "waveform"),
        Item(title: "Allow Multitasking", key: "allowMultitasking", icon: "rectangle.split.2x1"),
        Item(title: "Allow Apple Intelligence", key: "allowAppleIntelligence", icon: "apple.intelligence"),
        Item(title: "Allow NFC", key: "allowNFC", icon: "wave.3.right"),
        Item(title: "Allow AirDrop", key: "allowAirDrop", icon: "arrow.up.right.square"),
        Item(title: "Allow Paired Watch", key: "allowPairedWatch", icon: "applewatch"),
        Item(title: "Allow Profile Installation", key: "allowUIConfigurationProfileInstallation", icon: "person.text.rectangle"),
        Item(title: "Allow Account Modification", key: "allowAccountModification", icon: "person.crop.circle"),
        Item(title: "Allow Erase All Content And Settings", key: "allowEraseContentAndSettings", icon: "trash.circle")
    ]
    private let external = [
        Item(title: "Allow USB Restricted Mode", key: "allowUSBRestrictedMode", icon: "cable.connector"),
        Item(title: "Allow Proximity Setup", key: "allowProximitySetupToNewDevice", icon: "iphone.gen3.radiowaves.left.and.right")
    ]
    private let bypass = [
        Item(title: "Allow Screen Time", key: "allowScreenTime", icon: "hourglass"),
        Item(title: "Allow Classroom", key: "allowClassroom", icon: "person.3"),
        Item(title: "Allow Explicit Content", key: "allowExplicitContent", icon: "exclamationmark.triangle")
    ]

    var body: some View {
        List {
            Section {
                Text("These settings are delivered as an Apple configuration profile and require a supervised device.")
                    .font(.footnote)
                    .foregroundStyle(.secondary)
            }
            restrictionSection("Home Screen & Apps", items: home)
            restrictionSection("System", items: system)
            restrictionSection("External Features", items: external)
            restrictionSection("Bypass Features", items: bypass)
            Section {
                SupervisionInstallButton(profile: makeProfile())
            }
        }
        .navigationTitle("Restriction Tweaks")
        .onAppear {
            for item in home + system + external + bypass {
                let key = persistencePrefix + item.key
                if UserDefaults.standard.object(forKey: key) == nil {
                    values[item.key] = true
                    UserDefaults.standard.set(true, forKey: key)
                } else {
                    values[item.key] = UserDefaults.standard.bool(forKey: key)
                }
            }
        }
    }

    @ViewBuilder
    private func restrictionSection(_ title: String, items: [Item]) -> some View {
        Section {
            ForEach(items) { item in
                Toggle(isOn: Binding(
                    get: { values[item.key] ?? true },
                    set: { newValue in
                        values[item.key] = newValue
                        UserDefaults.standard.set(newValue, forKey: persistencePrefix + item.key)
                    }
                )) {
                    Label(item.title, systemImage: item.icon)
                }
            }
        } header: {
            HeaderLabel(title, symbol: "slider.horizontal.3")
        }
    }

    private func makeProfile() -> SupervisionProfile {
        var payload: [String: Any] = [:]
        for item in home + system + external + bypass { payload[item.key] = values[item.key] ?? true }
        payload["allowScreenTime"] = values["allowScreenTime"] ?? true
        payload["allowClassroom"] = values["allowClassroom"] ?? true
        payload["allowExplicitContent"] = values["allowExplicitContent"] ?? true
        return SupervisionProfile(fileName: "Erosion-Restrictions.mobileconfig", displayName: "Erosion Restriction Tweaks", payloadType: "com.apple.applicationaccess", payload: payload)
    }
}

private struct SupervisionNotificationsView: View {
    private struct AppSetting: Identifiable, Codable {
        var id = UUID()
        var bundleID = ""
        var notifications = true
        var notificationCenter = true
        var lockScreen = true
        var badges = true
        var sounds = true
        var carPlay = true
    }

    @State private var apps: [AppSetting] = []

    var body: some View {
        List {
            Section {
                Text("Notification settings are enforced by a supervised configuration profile. Add an app by its bundle identifier, then install the generated profile.")
                    .font(.footnote)
                    .foregroundStyle(.secondary)
            }
            Section {
                ForEach($apps) { $app in
                    VStack(alignment: .leading, spacing: 15) {
                        HStack {
                            TextField("Bundle Identifier", text: $app.bundleID)
                                .textInputAutocapitalization(.never)
                                .autocorrectionDisabled()
                            Button(role: .destructive) {
                                apps.removeAll { $0.id == app.id }
                            } label: { Image(systemName: "minus.circle.fill") }
                                .buttonStyle(.plain)
                        }
                        Toggle("Notifications Enabled", isOn: $app.notifications)
                        Toggle("Notification Center", isOn: $app.notificationCenter)
                        Toggle("Lock Screen", isOn: $app.lockScreen)
                        Toggle("Badges", isOn: $app.badges)
                        Toggle("Sounds", isOn: $app.sounds)
                        Toggle("CarPlay", isOn: $app.carPlay)
                    }
                    .padding(.vertical, 9)
                }
                Button {
                    apps.append(AppSetting())
                } label: {
                    Label("Add Application", systemImage: "plus")
                }
            } header: {
                HeaderLabel("Applications", symbol: "app.badge")
            }
            Section {
                Button("Install Profile") {
                    guard apps.allSatisfy({ !$0.bundleID.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty }) else {
                        Alertinator.shared.alert(title: "Missing Bundle Identifier", body: "Every notification entry needs a bundle identifier.")
                        return
                    }
                    let settings: [[String: Any]] = apps.map { app in
                        [
                            "BundleIdentifier": app.bundleID,
                            "NotificationsEnabled": app.notifications,
                            "ShowInNotificationCenter": app.notificationCenter,
                            "ShowInLockScreen": app.lockScreen,
                            "BadgesEnabled": app.badges,
                            "SoundsEnabled": app.sounds,
                            "ShowInCarPlay": app.carPlay
                        ]
                    }
                    let profile = SupervisionProfile(fileName: "Erosion-Notifications.mobileconfig", displayName: "Erosion Notification Settings", payloadType: "com.apple.notificationsettings", payload: ["NotificationSettings": settings])
                    SupervisionInstaller.install(profile)
                }
                .disabled(apps.isEmpty)
            }
        }
        .navigationTitle("Notification Settings")
    }
}

private struct SupervisionWebClipsView: View {
    @State private var label = ""
    @State private var url = ""
    @State private var removable = true
    @State private var fullScreen = false
    @State private var precomposed = false
    @State private var icon = Data()
    @State private var showPicker = false

    var body: some View {
        List {
            Section {
                TextField("Label", text: $label)
                TextField("URL", text: $url)
                    .textInputAutocapitalization(.never)
                    .autocorrectionDisabled()
                    .keyboardType(.URL)
                Toggle("Removable", isOn: $removable)
                Toggle("Full Screen", isOn: $fullScreen)
                Toggle("Precomposed Icon", isOn: $precomposed)
            } header: {
                HeaderLabel("Web Clip", symbol: "safari")
            }

            Section {
                Button {
                    showPicker = true
                } label: {
                    HStack {
                        Label("Choose Icon", systemImage: "photo")
                        Spacer()
                        if !icon.isEmpty { Image(systemName: "checkmark.circle.fill").foregroundStyle(.green) }
                    }
                }
                if !icon.isEmpty {
                    Button("Remove Icon", role: .destructive) { icon = Data() }
                }
            } header: {
                HeaderLabel("Icon", symbol: "app.gift")
            }

            Section {
                Button("Install Profile") {
                    let trimmed = url.trimmingCharacters(in: .whitespacesAndNewlines)
                    guard !label.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, !trimmed.isEmpty else {
                        Alertinator.shared.alert(title: "Missing Information", body: "Enter a label and URL first.")
                        return
                    }
                    guard let parsed = URL(string: trimmed), let scheme = parsed.scheme?.lowercased(), scheme == "http" || scheme == "https" else {
                        Alertinator.shared.alert(title: "Invalid URL", body: "The Web Clip URL must use http:// or https://.")
                        return
                    }
                    var payload: [String: Any] = [
                        "Label": label,
                        "URL": trimmed,
                        "IsRemovable": removable,
                        "FullScreen": fullScreen,
                        "Precomposed": precomposed
                    ]
                    if !icon.isEmpty { payload["Icon"] = icon }
                    let profile = SupervisionProfile(fileName: "Erosion-WebClip.mobileconfig", displayName: "Erosion Web Clip: \(label)", payloadType: "com.apple.webClip.managed", payload: payload)
                    SupervisionInstaller.install(profile)
                }
            }
        }
        .navigationTitle("Web Clips")
        .sheet(isPresented: $showPicker) {
            ImagePickerView { data in icon = data }
        }
    }
}
